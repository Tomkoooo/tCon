pub const QUICK_LABEL: &str = "quick";
pub const MAIN_LABEL: &str = "main";
pub const DEFAULT_SHORTCUT: &str = "Alt+Shift+Space";
pub const AUTOSTART_ARG: &str = "--autostart";
const TRAY_ID: &str = "tcon-tray";
const QUICK_W: f64 = 680.0;
const QUICK_H: f64 = 460.0;

/// The commands the quick panel webview may call. build.rs turns this list into the
/// `quick-panel` permission set (keep it a plain list of string literals).
pub const QUICK_COMMANDS: &[&str] = &[
    "tasks_load",
    "task_create",
    "task_update",
    "quick_projects",
    "quick_hide",
    "quick_open",
];

// ---------------- settings ----------------

#[derive(Clone, Debug, PartialEq, Deserialize)]
#[serde(rename_all = "camelCase", default)]
pub struct BgSettings {
    pub shortcut: String,
    pub keep_running: bool,
    pub show_tray: bool,
    pub launch_at_login: bool,
}

impl Default for BgSettings {
    fn default() -> Self {
        Self { shortcut: DEFAULT_SHORTCUT.into(), keep_running: true, show_tray: true, launch_at_login: false }
    }
}

/// Background settings from the text of ~/.tcon/settings.json (JSONC). Missing or
/// mistyped keys fall back to the defaults.
pub fn parse_settings(text: &str) -> BgSettings {
    let d = BgSettings::default();
    let v: serde_json::Value = serde_json::from_str(&crate::themes::strip_jsonc(text)).unwrap_or_default();
    let b = |k: &str, def: bool| v.get(k).and_then(|x| x.as_bool()).unwrap_or(def);
    BgSettings {
        shortcut: v.get("quickPanel.shortcut").and_then(|x| x.as_str()).map(str::to_string).unwrap_or(d.shortcut),
        keep_running: b("app.keepRunningInBackground", d.keep_running),
        show_tray: b("app.showTrayIcon", d.show_tray),
        launch_at_login: b("app.launchAtLogin", d.launch_at_login),
    }
}

fn read_settings_file() -> BgSettings {
    std::fs::read_to_string(crate::themes::tcon_dir().join("settings.json")).map(|t| parse_settings(&t)).unwrap_or_default()
}

// ---------------- shortcut parsing ----------------

/// Normalize a user-written shortcut ("⌥⇧Space", "option+shift+space", "Cmd+Alt+K") to the
/// canonical `Mod+Mod+Key` form the global-shortcut plugin parses ("Alt+Shift+Space").
/// Requires at least one modifier, except for function keys.
pub fn normalize_shortcut(input: &str) -> Result<String, String> {
    let s = input.trim();
    if s.is_empty() {
        return Err("Shortcut is empty".into());
    }
    // Expand macOS symbols into "+"-separated tokens.
    let mut expanded = String::new();
    for c in s.chars() {
        let sym = match c {
            '⌘' => Some("Cmd"),
            '⌥' => Some("Alt"),
            '⇧' => Some("Shift"),
            '⌃' => Some("Ctrl"),
            _ => None,
        };
        match sym {
            Some(m) => {
                expanded.push('+');
                expanded.push_str(m);
                expanded.push('+');
            }
            None => expanded.push(c),
        }
    }
    let tokens: Vec<&str> = expanded.split(|c: char| c == '+' || c == ' ').map(str::trim).filter(|t| !t.is_empty()).collect();
    // A lone "+" key isn't supported (it's the separator).
    let (mut ctrl, mut alt, mut shift, mut cmd, mut cmd_or_ctrl) = (false, false, false, false, false);
    let mut key: Option<String> = None;
    for t in tokens {
        let flag = match t.to_ascii_lowercase().as_str() {
            "ctrl" | "control" => &mut ctrl,
            "alt" | "option" | "opt" => &mut alt,
            "shift" => &mut shift,
            "cmd" | "command" | "super" | "meta" | "win" => &mut cmd,
            "cmdorctrl" | "commandorcontrol" | "cmdorcontrol" | "commandorctrl" => &mut cmd_or_ctrl,
            _ => {
                if key.is_some() {
                    return Err(format!("More than one key in \"{input}\""));
                }
                key = Some(normalize_key(t));
                continue;
            }
        };
        if *flag {
            return Err(format!("Repeated modifier in \"{input}\""));
        }
        *flag = true;
    }
    let Some(key) = key else { return Err(format!("\"{input}\" has no key, only modifiers")) };
    let is_fn = key.len() >= 2 && key.starts_with('F') && key[1..].parse::<u8>().is_ok_and(|n| (1..=24).contains(&n));
    if !(ctrl || alt || shift || cmd || cmd_or_ctrl) && !is_fn {
        return Err("Add a modifier (⌘, ⌥, ⌃ or ⇧) so normal typing isn't captured".into());
    }
    let mut parts: Vec<&str> = Vec::new();
    if cmd_or_ctrl {
        parts.push("CmdOrCtrl");
    }
    if ctrl {
        parts.push("Ctrl");
    }
    if alt {
        parts.push("Alt");
    }
    if shift {
        parts.push("Shift");
    }
    if cmd {
        parts.push("Cmd");
    }
    let canonical = format!("{}{}{}", parts.join("+"), if parts.is_empty() { "" } else { "+" }, key);
    canonical.parse::<Shortcut>().map_err(|e| format!("\"{input}\": {e}"))?;
    Ok(canonical)
}

fn normalize_key(t: &str) -> String {
    let lower = t.to_ascii_lowercase();
    if let Some(rest) = lower.strip_prefix("key").filter(|r| r.len() == 1) {
        return rest.to_ascii_uppercase();
    }
    if let Some(rest) = lower.strip_prefix("digit").filter(|r| r.len() == 1) {
        return rest.to_string();
    }
    if t.chars().count() == 1 {
        return t.to_uppercase();
    }
    let mut c = lower.chars();
    match c.next() {
        Some(f) => f.to_ascii_uppercase().to_string() + c.as_str(),
        None => String::new(),
    }
}

// ---------------- project list ----------------

#[derive(Serialize, Clone, Debug, PartialEq)]
#[serde(rename_all = "camelCase")]
pub struct QuickProject {
    pub path: String,
    pub name: String,
    pub color: Option<String>,
    /// Open as a tab in the main window.
    pub open: bool,
    /// The main window's active project.
    pub active: bool,
}

#[derive(Deserialize, Default)]
#[serde(rename_all = "camelCase", default)]
struct SnapProject {
    id: String,
    name: String,
    root_path: String,
    color: Option<String>,
}

#[derive(Deserialize, Default)]
#[serde(rename_all = "camelCase", default)]
struct Snapshot {
    order: Vec<String>,
    active_project_id: Option<String>,
    projects: Vec<SnapProject>,
}

fn trim_path(p: &str) -> &str {
    if p.len() > 1 { p.trim_end_matches('/') } else { p }
}

fn basename(p: &str) -> String {
    trim_path(p).rsplit('/').next().filter(|s| !s.is_empty()).unwrap_or(p).to_string()
}

/// The projects open in the main window (from its persisted workspace snapshot, in tab
/// order) followed by recent paths that aren't open. Duplicates (by path) are dropped.
pub fn merge_projects(snapshot_json: Option<&str>, recents: &[RecentPath]) -> Vec<QuickProject> {
    let snap: Snapshot = snapshot_json.and_then(|s| serde_json::from_str(s).ok()).unwrap_or_default();
    let mut out: Vec<QuickProject> = Vec::new();
    let push = |p: QuickProject, out: &mut Vec<QuickProject>| {
        if !p.path.is_empty() && !out.iter().any(|x| x.path == p.path) {
            out.push(p);
        }
    };
    for id in &snap.order {
        if let Some(p) = snap.projects.iter().find(|p| &p.id == id) {
            let path = trim_path(&p.root_path).to_string();
            let name = if p.name.trim().is_empty() { basename(&path) } else { p.name.clone() };
            let active = snap.active_project_id.as_deref() == Some(id.as_str());
            push(QuickProject { path, name, color: p.color.clone(), open: true, active }, &mut out);
        }
    }
    for r in recents {
        let path = trim_path(&r.path).to_string();
        push(QuickProject { name: basename(&path), path, color: None, open: false, active: false }, &mut out);
    }
    out
}

fn projects_from_db(db: &Db) -> Vec<QuickProject> {
    let snap = db.get_setting("workspace").ok().flatten();
    let recents = db.recent(30).unwrap_or_default();
    merge_projects(snap.as_deref(), &recents)
}

// ---------------- state ----------------

#[derive(Default)]
pub struct BgState {
    settings: Mutex<BgSettings>,
    registered: Mutex<Option<Shortcut>>,
    shortcut_error: Mutex<Option<String>>,
    /// Tray "Projects" submenu entries: menu id `proj:<i>` → path.
    tray_projects: Mutex<Vec<String>>,
    /// Whether the main window had focus when the quick panel was shown.
    main_was_focused: AtomicBool,
    /// When the quick panel was last shown (ms), to ignore the blur that can follow at once.
    shown_at: AtomicU64,
}

#[derive(Serialize)]
#[serde(rename_all = "camelCase")]
pub struct BgStatus {
    /// The shortcut in effect (canonical), or null when none is registered.
    pub shortcut: Option<String>,
    pub shortcut_error: Option<String>,
    pub launch_at_login: bool,
    pub default_shortcut: &'static str,
}

fn now_ms() -> u64 {
    SystemTime::now().duration_since(UNIX_EPOCH).map(|d| d.as_millis() as u64).unwrap_or(0)
}

/// Was tCon started by the login item (show only the tray)?
pub fn started_hidden() -> bool {
    std::env::args().any(|a| a == AUTOSTART_ARG || a == "--hidden")
}

// ---------------- plugins ----------------

pub fn shortcut_plugin() -> tauri::plugin::TauriPlugin<tauri::Wry> {
    tauri_plugin_global_shortcut::Builder::new()
        .with_handler(|app, _shortcut, event| {
            if event.state == ShortcutState::Pressed {
                toggle_quick(app);
            }
        })
        .build()
}

pub fn autostart_plugin() -> tauri::plugin::TauriPlugin<tauri::Wry> {
    let b = tauri_plugin_autostart::Builder::new().arg(AUTOSTART_ARG);
    #[cfg(target_os = "macos")]
    let b = b.macos_launcher(tauri_plugin_autostart::MacosLauncher::LaunchAgent);
    b.build()
}

// ---------------- setup ----------------

/// Called from the app's setup hook: state, quick window, tray, shortcut, login item.
pub fn setup(app: &AppHandle) -> tauri::Result<()> {
    app.manage(BgState::default());
    create_quick_window(app)?;
    let settings = read_settings_file();
    apply(app, settings);
    if started_hidden() {
        if let Some(w) = app.get_webview_window(MAIN_LABEL) {
            let _ = w.hide();
        }
    }
    Ok(())
}

/// Apply settings: (re-)register the shortcut, tray visibility and login item.
fn apply(app: &AppHandle, s: BgSettings) {
    let st = app.state::<BgState>();
    register_shortcut(app, &s.shortcut);
    // Login item: only touch it when it differs, never on our own initiative.
    let al = app.autolaunch();
    if al.is_enabled().unwrap_or(false) != s.launch_at_login {
        let _ = if s.launch_at_login { al.enable() } else { al.disable() };
    }
    *st.settings.lock() = s.clone();
    if s.show_tray {
        if app.tray_by_id(TRAY_ID).is_none() {
            if let Err(e) = create_tray(app) {
                eprintln!("tray: {e}");
            }
        } else {
            refresh_tray(app);
        }
    }
    if let Some(t) = app.tray_by_id(TRAY_ID) {
        let _ = t.set_visible(s.show_tray);
    }
}

fn register_shortcut(app: &AppHandle, wanted: &str) {
    let st = app.state::<BgState>();
    let gs = app.global_shortcut();
    let wanted_sc = normalize_shortcut(wanted).and_then(|c| c.parse::<Shortcut>().map_err(|e| e.to_string()));
    let mut reg = st.registered.lock();
    if let (Ok(new), Some(old)) = (&wanted_sc, reg.as_ref()) {
        if new == old {
            return;
        }
    }
    if let Some(old) = reg.take() {
        let _ = gs.unregister(old);
    }
    let err = match wanted_sc {
        Err(e) => Some(e),
        Ok(sc) => match gs.register(sc) {
            Ok(()) => {
                *reg = Some(sc);
                None
            }
            Err(e) => Some(format!("Couldn't register {}: {e}. Another app probably uses it.", wanted.trim())),
        },
    };
    *st.shortcut_error.lock() = err;
}

// ---------------- quick window ----------------

fn create_quick_window(app: &AppHandle) -> tauri::Result<()> {
    let b = WebviewWindowBuilder::new(app, QUICK_LABEL, WebviewUrl::App("index.html?view=quick".into()))
        .title("tCon Quick Add")
        .inner_size(QUICK_W, QUICK_H)
        .resizable(false)
        .maximizable(false)
        .minimizable(false)
        .visible(false)
        .focused(false)
        .always_on_top(true)
        .skip_taskbar(true)
        .visible_on_all_workspaces(true)
        .devtools(cfg!(debug_assertions));
    // macOS: a titled window with a hidden, transparent title bar gets native rounded corners
    // and shadow without the private API a transparent window would need. The traffic
    // lights are hidden in `macos_tweak`.
    #[cfg(target_os = "macos")]
    let b = b.decorations(true).title_bar_style(tauri::TitleBarStyle::Overlay).hidden_title(true);
    #[cfg(not(target_os = "macos"))]
    let b = b.decorations(false);
    let w = b.build()?;
    #[cfg(target_os = "macos")]
    macos_tweak(&w);
    let app2 = app.clone();
    w.on_window_event(move |ev| {
        if let tauri::WindowEvent::Focused(false) = ev {
            let st = app2.state::<BgState>();
            if now_ms().saturating_sub(st.shown_at.load(Ordering::Relaxed)) > 250 {
                if let Some(q) = app2.get_webview_window(QUICK_LABEL) {
                    let _ = q.hide();
                }
            }
        }
    });
    Ok(())
}

/// Hide the traffic lights, float above other apps (also over fullscreen apps, best
/// effort) and join every Space.
#[cfg(target_os = "macos")]
fn macos_tweak(w: &WebviewWindow) {
    use objc2_app_kit::{NSWindow, NSWindowButton, NSWindowCollectionBehavior};
    let Ok(ptr) = w.ns_window() else { return };
    // SAFETY: `ns_window` is the live NSWindow of this webview window; we're on the main
    // thread (setup hook).
    let ns: &NSWindow = unsafe { &*(ptr as *const NSWindow) };
    for b in [NSWindowButton::CloseButton, NSWindowButton::MiniaturizeButton, NSWindowButton::ZoomButton] {
        if let Some(btn) = ns.standardWindowButton(b) {
            btn.setHidden(true);
        }
    }
    ns.setCollectionBehavior(
        NSWindowCollectionBehavior::CanJoinAllSpaces
            | NSWindowCollectionBehavior::FullScreenAuxiliary
            | NSWindowCollectionBehavior::IgnoresCycle,
    );
    // NSStatusWindowLevel (25): above normal floating windows, like Spotlight.
    ns.setLevel(25);
}

/// Centre the quick panel on the monitor under the cursor, a bit above the middle.
fn position_quick(app: &AppHandle, w: &WebviewWindow) {
    let monitor = app
        .cursor_position()
        .ok()
        .and_then(|p| app.monitor_from_point(p.x, p.y).ok().flatten())
        .or_else(|| w.current_monitor().ok().flatten())
        .or_else(|| app.primary_monitor().ok().flatten());
    let Some(m) = monitor else { return };
    let scale = m.scale_factor();
    let (mx, my) = (m.position().x as f64, m.position().y as f64);
    let (mw, mh) = (m.size().width as f64, m.size().height as f64);
    let (ww, wh) = (QUICK_W * scale, QUICK_H * scale);
    let x = mx + (mw - ww) / 2.0;
    let y = my + ((mh - wh) * 0.32).max(0.0);
    let _ = w.set_position(tauri::PhysicalPosition::new(x.round() as i32, y.round() as i32));
}

pub fn show_quick(app: &AppHandle) {
    let Some(w) = app.get_webview_window(QUICK_LABEL) else { return };
    let st = app.state::<BgState>();
    let main_focused = app.get_webview_window(MAIN_LABEL).and_then(|m| m.is_focused().ok()).unwrap_or(false);
    st.main_was_focused.store(main_focused, Ordering::Relaxed);
    st.shown_at.store(now_ms(), Ordering::Relaxed);
    position_quick(app, &w);
    let _ = w.show();
    let _ = w.unminimize();
    let _ = w.set_focus();
    let _ = w.emit_to(QUICK_LABEL, "quick-shown", ());
}

/// Hide the quick panel. `restore_focus`: give focus back to the app that had it (macOS
/// hides tCon when its main window wasn't the focused one).
pub fn hide_quick(app: &AppHandle, restore_focus: bool) {
    if let Some(w) = app.get_webview_window(QUICK_LABEL) {
        let _ = w.hide();
    }
    #[cfg(target_os = "macos")]
    if restore_focus && !app.state::<BgState>().main_was_focused.load(Ordering::Relaxed) {
        let _ = app.hide();
    }
    #[cfg(not(target_os = "macos"))]
    let _ = restore_focus;
}

pub fn toggle_quick(app: &AppHandle) {
    let visible = app.get_webview_window(QUICK_LABEL).and_then(|w| w.is_visible().ok()).unwrap_or(false);
    if visible {
        hide_quick(app, true);
    } else {
        show_quick(app);
    }
}

pub fn show_main(app: &AppHandle) {
    if let Some(w) = app.get_webview_window(MAIN_LABEL) {
        let _ = w.show();
        let _ = w.unminimize();
        let _ = w.set_focus();
    }
}

#[derive(Serialize, Clone)]
#[serde(rename_all = "camelCase")]
struct OpenRequest {
    root: String,
    /// Open the board with this task's drawer; null: just switch to the project.
    task_id: Option<String>,
    /// Open the board even without a task.
    board: bool,
}

fn open_in_main(app: &AppHandle, root: String, task_id: Option<String>, board: bool) {
    hide_quick(app, false);
    show_main(app);
    let _ = app.emit_to(MAIN_LABEL, "quick-open", OpenRequest { root, task_id, board });
}

// ---------------- main window lifecycle ----------------

/// Main window close: hide instead of quitting when background mode is on.
pub fn on_main_close(window: &tauri::Window, api: &tauri::CloseRequestApi) {
    let app = window.app_handle();
    let keep = app.try_state::<BgState>().map(|s| s.settings.lock().keep_running).unwrap_or(false);
    if keep {
        api.prevent_close();
        let _ = window.hide();
    } else {
        // The hidden quick window would otherwise keep the app alive.
        app.exit(0);
    }
}

// ---------------- tray ----------------

fn build_tray_menu(app: &AppHandle) -> tauri::Result<Menu<tauri::Wry>> {
    let st = app.state::<BgState>();
    let settings = st.settings.lock().clone();
    let shortcut = st.registered.lock().is_some().then(|| normalize_shortcut(&settings.shortcut).ok()).flatten();
    let quick = MenuItem::with_id(app, "quick", "Quick Add…", true, shortcut.as_deref())
        .or_else(|_| MenuItem::with_id(app, "quick", "Quick Add…", true, None::<&str>))?;
    let open = MenuItem::with_id(app, "open", "Open tCon", true, None::<&str>)?;

    let projects = app.try_state::<Db>().map(|db| projects_from_db(&db)).unwrap_or_default();
    let projects: Vec<QuickProject> = projects.into_iter().take(12).collect();
    let items: Vec<MenuItem<tauri::Wry>> = projects
        .iter()
        .enumerate()
        .map(|(i, p)| MenuItem::with_id(app, format!("proj:{i}"), &p.name, true, None::<&str>))
        .collect::<tauri::Result<_>>()?;
    *st.tray_projects.lock() = projects.iter().map(|p| p.path.clone()).collect();
    let refs: Vec<&dyn tauri::menu::IsMenuItem<tauri::Wry>> = items.iter().map(|i| i as _).collect();
    let recent = Submenu::with_items(app, "Projects", !items.is_empty(), &refs)?;

    let login = CheckMenuItem::with_id(app, "login", "Launch at Login", true, app.autolaunch().is_enabled().unwrap_or(false), None::<&str>)?;
    let quit = MenuItem::with_id(app, "quit", "Quit tCon", true, None::<&str>)?;
    Menu::with_items(
        app,
        &[&quick, &PredefinedMenuItem::separator(app)?, &open, &recent, &PredefinedMenuItem::separator(app)?, &login, &PredefinedMenuItem::separator(app)?, &quit],
    )
}

fn create_tray(app: &AppHandle) -> tauri::Result<()> {
    let menu = build_tray_menu(app)?;
    TrayIconBuilder::with_id(TRAY_ID)
        .icon(tauri::include_image!("icons/tray.png"))
        .icon_as_template(true)
        .tooltip("tCon")
        .menu(&menu)
        .show_menu_on_left_click(true)
        .on_menu_event(|app, event| on_tray_menu(app, event.id().as_ref()))
        .build(app)?;
    Ok(())
}

/// Rebuild the tray menu (shortcut label, recent projects, login item state).
pub fn refresh_tray(app: &AppHandle) {
    let Some(tray) = app.tray_by_id(TRAY_ID) else { return };
    if let Ok(menu) = build_tray_menu(app) {
        let _ = tray.set_menu(Some(menu));
    }
}

fn on_tray_menu(app: &AppHandle, id: &str) {
    match id {
        "quick" => show_quick(app),
        "open" => show_main(app),
        "quit" => app.exit(0),
        "login" => {
            let al = app.autolaunch();
            let on = !al.is_enabled().unwrap_or(false);
            let _ = if on { al.enable() } else { al.disable() };
            app.state::<BgState>().settings.lock().launch_at_login = on;
            // The main window writes it to settings.json (keeps the file's comments).
            let _ = app.emit_to(MAIN_LABEL, "background-setting", ("app.launchAtLogin", on));
            refresh_tray(app);
        }
        _ => {
            if let Some(i) = id.strip_prefix("proj:").and_then(|n| n.parse::<usize>().ok()) {
                let path = app.state::<BgState>().tray_projects.lock().get(i).cloned();
                if let Some(path) = path {
                    open_in_main(app, path, None, false);
                }
            }
        }
    }
}

// ---------------- IPC guard ----------------

/// Defense in depth on top of capabilities/quick.json: the quick webview may only call
/// [`QUICK_COMMANDS`] and the event plugin.
pub fn guard_invoke<F>(handler: F) -> impl Fn(tauri::ipc::Invoke<tauri::Wry>) -> bool + Send + Sync + 'static
where
    F: Fn(tauri::ipc::Invoke<tauri::Wry>) -> bool + Send + Sync + 'static,
{
    move |invoke| {
        if invoke.message.webview_ref().label() == QUICK_LABEL {
            let cmd = invoke.message.command();
            if !QUICK_COMMANDS.contains(&cmd) && !cmd.starts_with("plugin:event|") {
                invoke.resolver.reject("command not available to the quick panel");
                return true;
            }
        }
        handler(invoke)
    }
}

