#[derive(Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct BgSettingsInput {
    shortcut: Option<String>,
    keep_running_in_background: Option<bool>,
    show_tray_icon: Option<bool>,
    launch_at_login: Option<bool>,
}

fn status(app: &AppHandle) -> BgStatus {
    let st = app.state::<BgState>();
    let shortcut = st.registered.lock().is_some().then(|| normalize_shortcut(&st.settings.lock().shortcut).ok()).flatten();
    BgStatus {
        shortcut,
        shortcut_error: st.shortcut_error.lock().clone(),
        launch_at_login: app.autolaunch().is_enabled().unwrap_or(false),
        default_shortcut: DEFAULT_SHORTCUT,
    }
}

/// Main window → apply the background settings from settings.json (sent whenever they change).
#[tauri::command]
pub fn background_apply(app: AppHandle, settings: BgSettingsInput) -> BgStatus {
    let d = BgSettings::default();
    let s = BgSettings {
        shortcut: settings.shortcut.filter(|s| !s.trim().is_empty()).unwrap_or(d.shortcut),
        keep_running: settings.keep_running_in_background.unwrap_or(d.keep_running),
        show_tray: settings.show_tray_icon.unwrap_or(d.show_tray),
        launch_at_login: settings.launch_at_login.unwrap_or(d.launch_at_login),
    };
    apply(&app, s);
    refresh_tray(&app);
    status(&app)
}

#[tauri::command]
pub fn background_status(app: AppHandle) -> BgStatus {
    status(&app)
}

/// Validate a shortcut string; returns its canonical form.
#[tauri::command]
