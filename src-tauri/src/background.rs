#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn normalizes_shortcuts() {
        assert_eq!(normalize_shortcut("Alt+Shift+Space").unwrap(), "Alt+Shift+Space");
        assert_eq!(normalize_shortcut("⌥⇧Space").unwrap(), "Alt+Shift+Space");
        assert_eq!(normalize_shortcut("⌥ Space").unwrap(), "Alt+Space");
        assert_eq!(normalize_shortcut("shift+option+space").unwrap(), "Alt+Shift+Space");
        assert_eq!(normalize_shortcut("cmd+ctrl+k").unwrap(), "Ctrl+Cmd+K");
        assert_eq!(normalize_shortcut("CmdOrCtrl+Shift+KeyT").unwrap(), "CmdOrCtrl+Shift+T");
        assert_eq!(normalize_shortcut("Ctrl+Digit1").unwrap(), "Ctrl+1");
        assert_eq!(normalize_shortcut("F13").unwrap(), "F13");
        assert_eq!(normalize_shortcut("  Super + Alt + Enter ").unwrap(), "Alt+Cmd+Enter");
    }

    #[test]
    fn rejects_bad_shortcuts() {
        assert!(normalize_shortcut("").is_err());
        assert!(normalize_shortcut("Space").is_err(), "no modifier");
        assert!(normalize_shortcut("K").is_err(), "no modifier");
        assert!(normalize_shortcut("Alt+Shift").is_err(), "no key");
        assert!(normalize_shortcut("Alt+K+J").is_err(), "two keys");
        assert!(normalize_shortcut("Alt+Alt+K").is_err(), "repeated modifier");
        assert!(normalize_shortcut("Alt+Banana").is_err(), "unknown key");
    }

    #[test]
    fn default_shortcut_is_valid() {
        assert_eq!(normalize_shortcut(DEFAULT_SHORTCUT).unwrap(), DEFAULT_SHORTCUT);
    }

    #[test]
    fn parses_settings_with_defaults() {
        assert_eq!(parse_settings(""), BgSettings::default());
        let s = parse_settings(
            r#"{
              // comment
              "quickPanel.shortcut": "⌘⇧K",
              "app.keepRunningInBackground": false,
              "app.launchAtLogin": true,
              "app.showTrayIcon": "nope", // wrong type → default
            }"#,
        );
        assert_eq!(s, BgSettings { shortcut: "⌘⇧K".into(), keep_running: false, show_tray: true, launch_at_login: true });
    }

    fn recent(path: &str) -> RecentPath {
        RecentPath { path: path.into(), last_used: 0, pinned: false }
    }

    #[test]
    fn merges_open_and_recent_projects() {
        let snap = r##"{"version":2,"order":["b","a"],"activeProjectId":"a","projects":[
            {"id":"a","name":"Alpha","rootPath":"/w/alpha/","color":"#fff","panes":{}},
            {"id":"b","name":"","rootPath":"/w/beta","color":"#000"},
            {"id":"zombie","name":"Gone","rootPath":"/w/gone"}]}"##;
        let out = merge_projects(Some(snap), &[recent("/w/alpha"), recent("/w/gamma/"), recent("/w/gamma"), recent("")]);
        let paths: Vec<&str> = out.iter().map(|p| p.path.as_str()).collect();
        assert_eq!(paths, ["/w/beta", "/w/alpha", "/w/gamma"]);
        assert_eq!(out[0].name, "beta");
        assert!(out[0].open && !out[0].active);
        assert!(out[1].open && out[1].active);
        assert_eq!(out[1].color.as_deref(), Some("#fff"));
        assert!(!out[2].open && out[2].color.is_none());
    }

    #[test]
    fn merges_without_snapshot() {
        assert!(merge_projects(None, &[]).is_empty());
        let out = merge_projects(Some("not json"), &[recent("/")]);
        assert_eq!(out.len(), 1);
        assert_eq!(out[0].path, "/");
    }
}
