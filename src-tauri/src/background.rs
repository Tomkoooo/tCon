//! Background mode: tCon stays resident with a tray / menu-bar icon, a global shortcut and a
//! Spotlight-like "quick panel" window (label `quick`) for adding and viewing tasks.
//!
//! - Closing the main window hides it (`app.keepRunningInBackground`, default true); ⌘Q and
//!   the tray's Quit still quit.
//! - `quickPanel.shortcut` (default ⌥⇧Space) toggles the quick panel from any app.
//! - `app.launchAtLogin` (default false) registers a LaunchAgent (macOS) / autostart entry
//!   that starts tCon with `--autostart`: the main window starts hidden, only the tray shows.
//! - `app.showTrayIcon` (default true).
//!
//! The settings live in ~/.tcon/settings.json. They're read here at startup, and the main
//! window pushes changes through `background_apply` whenever the file changes.
//!
//! Platform notes: the global shortcut and tray work on macOS, Windows and Linux/X11. On
//! Linux/Wayland, compositors don't let apps grab global shortcuts (register succeeds or
//! fails silently depending on the compositor; bind a desktop shortcut to `tcon` instead),
//! and the tray needs a StatusNotifier/AppIndicator host (e.g. GNOME needs an extension).
//!
//! Security: the quick webview gets IPC only through capabilities/quick.json, which grants
//! the `quick-panel` permission set generated by build.rs from [`QUICK_COMMANDS`].
//! [`guard_invoke`] enforces the same list again (defense in depth).
use std::sync::atomic::{AtomicBool, AtomicU64, Ordering};
use std::time::{SystemTime, UNIX_EPOCH};

