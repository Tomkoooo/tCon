use std::path::Path;

/// Turns on Tauri's ACL for tCon's own commands.
///
/// Without an app permission manifest, every webview at a local origin may call every
/// `#[tauri::command]` regardless of capabilities. We generate one permission set,
/// `app-commands`, holding all commands registered in `generate_handler!` in src/lib.rs,
/// and grant it only to the `main` webview (capabilities/default.json). Child webviews
/// (e.g. the integrated browser's `browser-*`) therefore get no IPC at all.
///
/// New commands are picked up automatically: just register them in `generate_handler!`.
fn main() {
    println!("cargo:rerun-if-changed=src/lib.rs");
    let lib = std::fs::read_to_string("src/lib.rs").expect("read src/lib.rs");
    let commands = handler_commands(&lib);
    assert!(!commands.is_empty(), "no commands found in generate_handler! in src/lib.rs");

    let list = commands.iter().map(|c| format!("  \"{c}\",")).collect::<Vec<_>>().join("\n");
    let toml = format!(
        "# Generated by build.rs from generate_handler! in src/lib.rs. Do not edit.\n\n\
         [[permission]]\n\
         identifier = \"app-commands\"\n\
         description = \"All of tCon's own commands. Granted to the main webview only.\"\n\
         commands.allow = [\n{list}\n]\n"
    );
    let dir = Path::new("permissions");
    std::fs::create_dir_all(dir).expect("create permissions dir");
    let path = dir.join("app-commands.toml");
    if std::fs::read_to_string(&path).ok().as_deref() != Some(toml.as_str()) {
        std::fs::write(&path, toml).expect("write permissions/app-commands.toml");
    }

    // `quick-panel`: the small subset the quick panel webview may call (capabilities/quick.json),
    // from `QUICK_COMMANDS` in src/background.rs.
    println!("cargo:rerun-if-changed=src/background.rs");
    let bg = std::fs::read_to_string("src/background.rs").expect("read src/background.rs");
    let quick = quick_commands(&bg);
    assert!(!quick.is_empty(), "no QUICK_COMMANDS found in src/background.rs");
    for c in &quick {
        assert!(commands.contains(c), "QUICK_COMMANDS lists {c}, which isn't registered in generate_handler!");
    }
    let list = quick.iter().map(|c| format!("  \"{c}\",")).collect::<Vec<_>>().join("\n");
    let toml = format!(
        "# Generated by build.rs from QUICK_COMMANDS in src/background.rs. Do not edit.\n\n\
         [[permission]]\n\
         identifier = \"quick-panel\"\n\
         description = \"The commands the quick panel window needs: task board read/add and its own show/hide/open.\"\n\
         commands.allow = [\n{list}\n]\n"
    );
    let path = dir.join("quick-panel.toml");
    if std::fs::read_to_string(&path).ok().as_deref() != Some(toml.as_str()) {
        std::fs::write(&path, toml).expect("write permissions/quick-panel.toml");
    }

    tauri_build::build()
}

/// Command names (last path segment) listed in `tauri::generate_handler![...]`.
fn handler_commands(src: &str) -> Vec<String> {
    let Some(start) = src.find("generate_handler![") else { return vec![] };
    let body = &src[start + "generate_handler![".len()..];
    let body = &body[..body.find(']').unwrap_or(body.len())];
    body.lines()
        .map(|l| l.split("//").next().unwrap_or(""))
        .flat_map(|l| l.split(','))
        .map(|s| s.trim())
        .filter(|s| !s.is_empty())
        .map(|s| s.rsplit("::").next().unwrap_or(s).to_string())
        .filter(|s| s.chars().all(|c| c.is_ascii_alphanumeric() || c == '_'))
        .collect()
}

/// String literals in `pub const QUICK_COMMANDS: &[&str] = &[...];`.
fn quick_commands(src: &str) -> Vec<String> {
    let Some(start) = src.find("QUICK_COMMANDS: &[&str] = &[") else { return vec![] };
    let body = &src[start + "QUICK_COMMANDS: &[&str] = &[".len()..];
    let body = &body[..body.find("];").unwrap_or(body.len())];
    body.split(',')
        .map(|s| s.trim().trim_matches('"').to_string())
        .filter(|s| !s.is_empty() && s.chars().all(|c| c.is_ascii_alphanumeric() || c == '_'))
        .collect()
}
